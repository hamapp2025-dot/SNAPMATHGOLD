#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const LESSONS_DIR = path.join(PROJECT_ROOT, 'assets/media/lessons');
const OUTPUT = path.join(PROJECT_ROOT, 'src/media/lessonMediaOverrides.generated.ts');

function pickHeroAsset(lessonId) {
  const candidates = [
    `${lessonId}-hero-subtitled-voiced.mp4`,
    `${lessonId}-hero-subtitled.mp4`,
    `${lessonId}-hero-voiced.mp4`,
    `${lessonId}-hero.mp4`,
    `${lessonId}-hero-visual.mp4`,
  ];

  for (const filename of candidates) {
    if (fs.existsSync(path.join(LESSONS_DIR, filename))) {
      return filename;
    }
  }

  return null;
}

function pickPosterAsset(lessonId) {
  const filename = `${lessonId}-poster.jpg`;
  return fs.existsSync(path.join(LESSONS_DIR, filename)) ? filename : null;
}

function main() {
  const catalog = JSON.parse(
    fs.readFileSync(path.join(PROJECT_ROOT, 'tools/lesson_hero_catalog.json'), 'utf8'),
  );

  const lines = [
    '// Auto-generated by scripts/generate-lesson-media-overrides.js — do not edit by hand.',
    '',
    'export const LESSON_MEDIA_ASSET_OVERRIDES = {',
  ];

  let count = 0;
  for (const lesson of catalog) {
    const hero = pickHeroAsset(lesson.id);
    const poster = pickPosterAsset(lesson.id);
    if (!hero && !poster) continue;

    lines.push(`  '${lesson.id}': {`);
    if (hero) {
      lines.push(`    heroVideoSource: require('../../assets/media/lessons/${hero}'),`);
    }
    if (poster) {
      lines.push(`    posterSource: require('../../assets/media/lessons/${poster}'),`);
    }
    lines.push('  },');
    count += 1;
  }

  lines.push('} as const;', '');

  fs.writeFileSync(OUTPUT, lines.join('\n'), 'utf8');
  console.log(`Wrote ${count} lesson media overrides -> ${path.relative(PROJECT_ROOT, OUTPUT)}`);
}

main();
